export function hasDevice3D(kind: Kind) {
  const def = DEFINITIONS[kind];
  return ['contactor', 'pushbutton', 'relay', 'timer'].includes(def.family ?? '') ||
    (def.family === 'breaker' && def.capability !== 'wiring') ||
    ['vfd', 'softStarter', 'motor'].includes(kind);
}
const normalizeSearch = (text: string) => text.toLowerCase().replace(/(\d)\s+(v|a|hz)\b/g, '$1$2');
export function filterKnowledge(search: string, category = '', group = '') {
  const words = normalizeSearch(search).trim().split(/\s+/).filter(Boolean);
  return KNOWLEDGE_KINDS.filter((kind) => {
    const def = DEFINITIONS[kind], entry = knowledgeFor(kind);
    const metadata = normalizeSearch([def.name, def.spec, def.category, def.group, kind,
      ...def.ports.map((p) => p.label), manufacturerSearchText(kind)].join(' '));
    const text = normalizeSearch([metadata, entry.title, entry.purpose,
      entry.principle, ...entry.applications, ...entry.specifications.flat(), ...entry.selection,
      ...entry.mistakes].join(' '));
    return (!category || def.category === category) && (!group || def.group === group) &&
      words.every((word) => (/\d/.test(word) ? metadata : text).includes(word));
  });
}
export function kindFromHash(hash: string): Kind | null {
  try {
    const id = decodeURIComponent(hash.replace(/^#/, ''));
    return Object.hasOwn(DEFINITIONS, id) ? id as Kind : null;
  } catch { return null; }
}

